// A página de um herói: só o que o cartão mostra, nos textos da língua.
function paginaDoHeroi(nome, t) {
  const h = H.acharHeroi(nome);
  const f = t.ficha;
  const linhas = [`{{ks_brilho}} **${h.name}**`, `{{${({ infantry: "ks_tropa_infantaria", cavalry: "ks_tropa_cavalaria", archer: "ks_tropa_arqueiro" })[h.troop]}}} ${f.tropa[h.troop]}`,
    `{{ks_fogo_${({ legendary: "lendario", epic: "epico", rare: "raro" })[h.rarity]}}} **${f.raridade[h.rarity]}**`];
  const fun = H.funcoesDoHeroi(h);
  const nota = { "S+": "splus", S: "s", A: "a", B: "b", C: "c", D: "d", "-": "nada" };
  const icone = { bear: "ks_urso", rally: "ks_rally", garrison: "ks_guarnicao" };
  fun.forEach(([k, v], i) => linhas.push(`{{${i === fun.length - 1 ? "ks_galho_fim" : "ks_galho"}}}{{${icone[k]}}} {{ks_nota_${nota[v] || "nada"}}} ${f.funcao[k]}`));
  if (H.ehF2P(h)) linhas.push(`> {{ks_bau}} *${f.f2p}*`);
  return { linhas: linhas.join("\n"), retrato: `img/herois/${h.name.toLowerCase().replace(/[^a-z0-9]/g, "")}.gif`, cor: "#" + H.COR_DA_RARIDADE[h.rarity].toString(16).padStart(6, "0") };
}

